import * as XLSX from "xlsx";
import { addTable, A4_WIDE, brandHeader, newPdf, pageFooter } from "@/lib/pdf";
import type { ReportColumn, ReportTemplate } from "@/lib/reports/templates";
import { neutraliseCell, toCsv } from "@/lib/validation/columns";

type Row = Record<string, unknown>;

const stamp = () => new Date().toISOString().slice(0, 16).replace("T", " ");

export function reportCsv(columns: ReportColumn[], rows: Row[]): string {
  return toCsv(columns.map((c) => c.key), rows);
}

export function reportXlsx(title: string, columns: ReportColumn[], rows: Row[]): Uint8Array {
  const header = columns.map((c) => c.header);
  const body = rows.map((r) => columns.map((c) => {
    const v = r[c.key];
    return typeof v === "number" ? v : neutraliseCell(v === null || v === undefined ? "" : String(v));
  }));
  const sheet = XLSX.utils.aoa_to_sheet([header, ...body]);
  const book = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(book, sheet, title.replace(/[\\/?*[\]:]/g, " ").slice(0, 31));
  return new Uint8Array(XLSX.write(book, { type: "buffer", bookType: "xlsx" }) as Buffer);
}

export async function reportPdf(template: ReportTemplate, rows: Row[], subtitle: string): Promise<Uint8Array> {
  const { doc, fonts } = await newPdf(template.title);
  addTable(doc, fonts, { columns: template.columns, rows }, { title: template.title, subtitle, footer: `Generated by Sutra on ${stamp()} UTC. ${rows.length} rows.` });
  return doc.save();
}

export async function accreditationPdf(institution: { name: string; aicte_id: string; state: string }, sections: { template: ReportTemplate; rows: Row[] }[]): Promise<Uint8Array> {
  const { doc, fonts } = await newPdf(`Accreditation pack: ${institution.name}`);
  const cover = doc.addPage([A4_WIDE.w, A4_WIDE.h]);
  brandHeader(cover, fonts, "Accreditation Pack", institution.name);
  cover.drawText(`AICTE ID ${institution.aicte_id}, ${institution.state}`, { x: 36, y: A4_WIDE.h - 150, size: 12, font: fonts.regular });
  cover.drawText(`Prepared ${stamp()} UTC`, { x: 36, y: A4_WIDE.h - 170, size: 12, font: fonts.regular });
  cover.drawText("Contents", { x: 36, y: A4_WIDE.h - 210, size: 13, font: fonts.bold });
  sections.forEach((s, i) => cover.drawText(`${i + 1}. ${s.template.title}: ${s.rows.length} rows`, { x: 48, y: A4_WIDE.h - 232 - i * 18, size: 11, font: fonts.regular }));
  pageFooter(cover, fonts, "Generated from verified records in Sutra.");
  for (const s of sections) {
    addTable(doc, fonts, { columns: s.template.columns, rows: s.rows }, { title: s.template.title, subtitle: institution.name, footer: `Accreditation pack for ${institution.name}.` });
  }
  return doc.save();
}
